// Optional browser checks. Supply a local Playwright installation; no runtime dependency.
const { chromium } = require(process.env.SOWERS_PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const base = process.env.SOWERS_URL || 'http://127.0.0.1:5286'
const output = '.cache/sowers-browser'
fs.mkdirSync(output,{recursive:true})
let browser

;(async()=>{
 browser=await chromium.launch({headless:true,
  ...(process.env.SOWERS_CHROME ? {executablePath:process.env.SOWERS_CHROME} : {}),
  args:['--use-angle=swiftshader','--enable-webgl','--ignore-gpu-blocklist']})
 const errors=[]
 const page=await browser.newPage({viewport:{width:1440,height:1000}})
 page.setDefaultTimeout(15000)
 page.on('pageerror',error=>errors.push(error.message))
 await page.goto(`${base}/sowers/?preview=1`)
 await page.locator('.crew-row').first().waitFor()
 assert.equal(await page.locator('.crew-row').count(),3)
 assert.equal(await page.locator('#checkpoint-count').innerText(),'6')
 await page.locator('.crew-row').filter({hasText:'Moss'}).click()
 assert.match(await page.locator('#detail').innerText(),/1 REPORTED CHECKPOINT/)
 await page.locator('#search').fill('Fern')
 assert.equal(await page.locator('.crew-row').count(),1)
 await page.locator('#search').fill('')
 await page.locator('#broadcast').click()
 assert.equal(await page.locator('#app').evaluate(node=>node.classList.contains('broadcast')),true)
 await page.keyboard.press('Escape')
 assert.equal(await page.locator('#app').evaluate(node=>node.classList.contains('broadcast')),false)
 await page.locator('#motion').click()
 assert.equal(await page.locator('#motion').getAttribute('aria-pressed'),'true')
 await page.screenshot({path:`${output}/mission-desktop.png`})
 console.log('Passed preview controls')

 // A matching broadcast adds checkpoints but cannot falsify native running state.
 const fixture=Array.from({length:12},(_,i)=>({id:`fixture:${i}`,title:i===0?'<img src=x onerror=alert(1)>':`Agent ${i}`,project:'Fixture base',running:i===0,lastActivityAt:Date.now(),harness:'codex'}))
 await page.route('**/api/threads',route=>route.fulfill({json:{threads:fixture,warnings:[]}}))
 await page.route('**/api/sowers/broadcast',route=>route.fulfill({json:{configured:true,threads:[{id:'fixture:0',running:false,broadcastStale:false,constructionProgress:.5,milestones:[{id:'proof',title:'Validated work',accepted:true,status:'accepted'}]}],warnings:[]}}))
 await page.goto(`${base}/sowers/`)
 await page.locator('.crew-row').first().waitFor()
 assert.equal(await page.locator('.crew-row').count(),9)
 assert.match(await page.locator('#detail').innerText(),/Working in the field/)
 assert.match(await page.locator('#detail').innerText(),/1 REPORTED CHECKPOINT/)
 assert.equal(await page.locator('#detail img').count(),0)
 await page.locator('#next').click()
 assert.equal(await page.locator('.crew-row').count(),3)
 await page.locator('#scope').selectOption('active')
 assert.equal(await page.locator('.crew-row').count(),1)
 await page.locator('#search').fill('no matching name')
 assert.equal(await page.locator('.crew-row').count(),0)
 assert.equal(await page.locator('#detail h2').innerText(),'Waiting for a signal')

 // An in-flight local request must never overwrite a mode switch to preview.
 await page.route('**/api/threads',async route=>{
  await new Promise(resolve=>setTimeout(resolve,500))
  await route.fulfill({json:{threads:fixture,warnings:[]}}).catch(()=>{})
 })
 await page.goto(`${base}/sowers/`)
 await page.locator('[data-mode="demo"]').click()
 await page.waitForTimeout(650)
 assert.equal(await page.locator('#checkpoint-count').innerText(),'6')
 assert.match(await page.locator('#connection').innerText(),/fictional/)
 console.log('Passed live-source fixtures and mode-switch race')

 await page.setViewportSize({width:390,height:844})
 await page.screenshot({path:`${output}/mission-mobile.png`})
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
 const context=await browser.newContext({viewport:{width:1280,height:900},reducedMotion:'reduce'})
 context.setDefaultTimeout(15000)
 const studio=await context.newPage()
 studio.on('pageerror',error=>errors.push(error.message))
 await studio.goto(`${base}/sowers/studio/`)
 await studio.locator('[data-status="complete"]').click()
 assert.equal(await studio.locator('[data-status="complete"]').getAttribute('aria-pressed'),'true')
 await studio.locator('[data-view="detail"]').click()
 await studio.screenshot({path:`${output}/studio-detail.png`})
 assert.match(await studio.locator('#play').innerText(),/Play/)
 console.log('Passed studio and compact layout')

 const pausedMission=await context.newPage()
 pausedMission.on('pageerror',error=>errors.push(error.message))
 await pausedMission.goto(`${base}/sowers/?preview=1`)
 assert.equal(await pausedMission.locator('#motion').getAttribute('aria-label'),'Resume motion')
 const beforeCamera=await pausedMission.locator('canvas').screenshot()
 await pausedMission.locator('canvas').focus()
 await pausedMission.keyboard.press('ArrowLeft')
 const afterCamera=await pausedMission.locator('canvas').screenshot()
 assert.notDeepEqual(beforeCamera,afterCamera,'Paused keyboard camera input must repaint')
 console.log('Passed paused keyboard repaint')

 const assembly=await context.newPage()
 assembly.on('pageerror',error=>errors.push(error.message))
 await assembly.goto(`${base}/sowers/assembly/`)
 await assembly.locator('[data-kind="relay"]').click()
 assert.equal(await assembly.locator('#model-kind').innerText(),'RELAY')
 await assembly.locator('[data-stage="1"]').click()
 assert.equal(await assembly.locator('[data-stage="1"]').getAttribute('aria-pressed'),'true')
 await assembly.locator('#mode').selectOption('checkpoints')
 assert.match(await assembly.locator('#completion').innerText(),/Unknown/)
 await assembly.locator('#add').click()
 assert.equal(await assembly.locator('#checkpoint-count').innerText(),'1')
 await assembly.locator('#retract').click()
 assert.equal(await assembly.locator('#checkpoint-count').innerText(),'0')
 await assembly.screenshot({path:`${output}/assembly-study.png`})
 console.log('Passed assembly evidence isolation')

 const fallback=await browser.newPage({viewport:{width:1200,height:900}})
 fallback.on('pageerror',error=>errors.push(error.message))
 await fallback.addInitScript(()=>{
  const original=HTMLCanvasElement.prototype.getContext
  HTMLCanvasElement.prototype.getContext=function(type,...args){return String(type).includes('webgl')?null:original.call(this,type,...args)}
 })
 await fallback.goto(`${base}/sowers/?preview=1`)
 await fallback.locator('.crew-row').last().click()
 assert.equal(await fallback.locator('.fallback').count(),1)
 assert.match(await fallback.locator('#detail').innerText(),/Moss/)
 assert.deepEqual(errors,[])
 console.log(JSON.stringify({passed:true,checks:['preview checkpoint totals','selection and search','broadcast and Escape','motion pause','live source merge','pagination and scope','text escaping','mode-switch race','mobile overflow','studio reduced motion','paused keyboard repaint','assembly evidence isolation','WebGL fallback'],pageErrors:errors,screenshots:output},null,2))
 await browser.close()
})().catch(async error=>{console.error(error);await browser?.close();process.exitCode=1})
