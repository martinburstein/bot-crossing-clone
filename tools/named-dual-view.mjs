import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const versions=JSON.parse(await fs.readFile(path.join(root,'DUAL-VIEW-VERSIONS.json'),'utf8'));
const name=process.argv.find(v=>Object.hasOwn(versions.versions,v));
if(!name)throw Error('Choose big-crypto-short or waveshare-arm.');
const selected=versions.versions[name];
if(process.argv.includes('--describe'))console.log(JSON.stringify({name,...selected,modelCalls:0,hardwareStartup:false}));
else await import(pathToFileURL(path.join(root,'tools',selected.launcher)).href);
