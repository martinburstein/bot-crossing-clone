// Runs the explicitly labeled visual fixture. Never activates the Swarm.
const fs=require('node:fs/promises'),path=require('node:path'),assert=require('node:assert/strict')
const {chromium}=require(process.env.BOT_CROSSING_PLAYWRIGHT||'@playwright/test')
;(async()=>{
  const base=process.env.BOT_CROSSING_TEST_URL
  if(!base||new URL(base).hostname!=='127.0.0.1')throw Error('Set BOT_CROSSING_TEST_URL to the existing local Vite server')
  const out=path.resolve('.cache/vehicle-missions-check');await fs.mkdir(out,{recursive:true})
  const browser=await chromium.launch({headless:true,channel:'chrome'})
  try {
    const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[]
    page.on('pageerror',e=>errors.push(e.message))
    await page.goto(new URL('/tools/visual-check/magi.html',base).href)
    await page.waitForFunction(()=>!!window.magiVisualCheck)
    const snapshot=()=>page.evaluate(()=>window.magiVisualCheck.snapshot())
    await page.click('#active');await page.waitForFunction(()=>window.magiVisualCheck.snapshot().fleet.length===3)
    let state=await snapshot();assert.equal(state.mounted,3);assert.equal(state.idle,12)
    assert.deepEqual(state.fleet.map(v=>v.job),['cargo','posts','reports'])
    const before=state.fleet.map(v=>v.position)
    await page.click('#step');state=await snapshot()
    assert.ok(state.fleet.every((v,i)=>Math.hypot(v.position[0]-before[i][0],v.position[2]-before[i][2])>5))
    assert.ok(state.fleet.every(v=>!v.routeBlocked),'The real colony fixture must have usable mission routes')
    await page.screenshot({path:path.join(out,'three-active-missions.png')})
    await page.click('#driver');await page.waitForTimeout(700)
    await page.screenshot({path:path.join(out,'cargo-mission.png')})
    await page.evaluate(()=>window.magiVisualCheck.advance(90));state=await snapshot()
    assert.ok(state.fleet.filter(v=>['cargo','reports'].includes(v.job)).every(v=>v.visitedStops.includes(0)&&v.visitedStops.includes(v.job==='reports'?2:1)),'Cargo and reports must reach their outer work-front stops')
    const oldFronts=await page.evaluate(()=>window.magiVisualCheck.fronts())
    await page.evaluate(()=>{window.magiVisualCheck.growAll(1000000);window.magiVisualCheck.advance(120)})
    const grownFronts=await page.evaluate(()=>window.magiVisualCheck.fronts());state=await snapshot()
    assert.ok(grownFronts.every((f,i)=>Math.hypot(f.stops[0][0],f.stops[0][2])>Math.hypot(oldFronts[i].stops[0][0],oldFronts[i].stops[0][2])),'Growing groups must move work to the new outer rim')
    assert.ok(state.fleet.every(v=>!v.routeBlocked),'Grown-colony outer work fronts must remain reachable')
    await page.click('#overview');await page.waitForTimeout(700);await page.screenshot({path:path.join(out,'grown-outer-work-fronts.png')})
    await page.evaluate(()=>window.magiVisualCheck.task(0,'Intercept an incoming large meteor'))
    await page.waitForFunction(()=>window.magiVisualCheck.snapshot().fleet.some(v=>v.vehicle==='defender'))
    await page.evaluate(()=>{for(let i=0;i<70;i++){window.magiVisualCheck.advance(1);if(window.magiVisualCheck.snapshot().fleet.some(v=>v.vehicle==='defender'&&v.beamVisible))break}window.magiVisualCheck.pause(true);window.magiVisualCheck.focusWorker('w01')})
    assert.ok((await snapshot()).fleet.some(v=>v.vehicle==='defender'&&v.meteorVisible&&v.beamVisible))
    await page.waitForTimeout(700)
    await page.screenshot({path:path.join(out,'meteor-defense.png')})
    await page.evaluate(()=>window.magiVisualCheck.pause(false))
    await page.click('#unknown');await page.waitForFunction(()=>window.magiVisualCheck.snapshot().fleet.length===0)
    assert.equal((await snapshot()).mounted,0)
    await page.screenshot({path:path.join(out,'disconnected-parked.png')})
    assert.deepEqual(errors,[])
    console.log(JSON.stringify({passed:true,activePilots:3,restingBots:12,jobs:['cargo','posts','reports'],realColonyRoutes:true,meteorDefense:true,disconnectParksImmediately:true,modelCalls:0,output:out}))
  }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1})
